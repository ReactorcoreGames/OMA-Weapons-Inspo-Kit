"""Kit handling derivations on top of Classic: hipfire tightening (merge rule 3) and
ads_run_instability (merge rule 4). Reasoning and tables: docs/research/hipfire-and-run-ads.md.

  heft(mass)          0 for a 0.8 kg weapon .. 1 for 20 kg and up (log scale)
  hip_divisor(mass)   2.7 (Pro's median tightening) for light weapons .. 1.3 for the heaviest;
                      ~2.0 for a 3.8 kg rifle. Divides Classic's hip drift cone (min and max).
  ads_run_instability 0 = rock steady aiming while running .. 1 = can't aim while running
                      (weapon drops to low-ready; the trigger still works).

Usage (review table): python tools/kit/handling_model.py <bw_kit_units.json> <out.md>
"""
import json
import math
import os
import sys

LIGHT_KG, HEAVY_KG = 0.8, 20.0
HIP_DIV_LIGHT, HIP_DIV_HEAVY = 2.7, 1.3   # Pro's median hip-cone ratio was 1 / 0.37 = 2.7


def heft(mass_kg):
    """0..1 log-scaled heaviness. Unclamped inputs are fine; the result is clamped to 0..1."""
    if mass_kg is None or mass_kg <= 0:
        return 0.0
    return min(1.0, max(0.0, math.log(mass_kg / LIGHT_KG) / math.log(HEAVY_KG / LIGHT_KG)))


def hip_divisor(mass_kg):
    """How much tighter than Classic the kit's hip drift cone is. Light weapons lean to Pro's 2.7x."""
    return HIP_DIV_LIGHT - (HIP_DIV_LIGHT - HIP_DIV_HEAVY) * heft(mass_kg)


def scope_floor(zoom_max):
    """Magnified optics are hard to keep on target while running, whatever the weapon weighs."""
    if not zoom_max or zoom_max < 2:
        return 0.0
    if zoom_max < 4:
        return 0.5
    if zoom_max < 8:
        return 0.9
    return 1.0


def ads_run_instability(mass_kg, hold="shouldered", zoom_max=None, melee=False):
    """0..1 (values above 1 behave like 1). Base is heft; hip-braced heavies are always 1; magnified
    optics set a floor; melee weapons aim nothing and get 0."""
    if melee:
        return 0.0
    if hold == "hip_braced":
        return 1.0
    base = heft(mass_kg)
    if hold in ("one_hand", "two_hand"):
        base *= 0.8  # handguns ride the arms' own suspension better than a shoulder stock
    return round(max(base, scope_floor(zoom_max)), 2)


def movement_chaos(jump_chaos, sprint_chaos, mass_kg):
    """Defaults for kit-new movement (dodge, slide, wall-run); heavier weapons suffer more."""
    k = 1.0 + heft(mass_kg)
    return {"dodge_chaos": round(jump_chaos * k, 3), "slide_chaos": round(max(jump_chaos, sprint_chaos) * k, 3),
            "wallrun_chaos": round(sprint_chaos * k, 3)}


def tightened_drift(drift_min_deg, drift_max_deg, mass_kg):
    d = hip_divisor(mass_kg)
    return (None if drift_min_deg is None else round(drift_min_deg / d, 3),
            None if drift_max_deg is None else round(drift_max_deg / d, 3))


# ---------- review table ----------
def report(kit_units_path, out_md):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import recoil_model as rm
    data = json.load(open(kit_units_path, encoding="utf-8"))["weapons"]
    rows = []
    for cls, w in sorted(data.items()):
        if not w["registered"] or not w["layouts"] or w["weapon"].get("aim_disabled"):
            continue
        L = w["layouts"][0]
        a = (L.get("aim") or [{}])[0]
        if not a.get("drift_max_deg"):
            continue
        mass = rm.BULK_MASS_KG.get(L.get("bulk"), 4.0)
        hold = rm.default_hold(w, L)
        lo, hi = tightened_drift(a.get("drift_min_deg"), a.get("drift_max_deg"), mass)
        rows.append((L.get("bulk"), cls, mass, hold, a.get("drift_min_deg"), a.get("drift_max_deg"), round(hip_divisor(mass), 2), lo, hi,
                     ads_run_instability(mass, hold, L.get("zoom_max") if L.get("zoom_type") != "irons" else None, bool(w["weapon"].get("melee_weapon")))))
    lines = ["# Hipfire and run-ADS review table (generated)", "",
             "Generated by `tools/kit/handling_model.py` from `bw_kit_units.json`: registered BW weapons with aim, default layout, bulk-based default mass and hold. "
             "Drift is the half-angle of BW's aim-drift cone: `min` at rest, `max` at full chaos (running, turning, jumping). Weapon entries recompute with their chosen mass.", "",
             "| Bulk | BW class | Mass kg | Hold | Classic drift min / max deg | Divisor | Kit drift min / max deg | ads_run_instability |",
             "|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows):
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} / {r[5]} | {r[6]} | {r[7]} / {r[8]} | {r[9]} |")
    with open(out_md, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(rows)} weapons -> {out_md}")


if __name__ == "__main__":
    report(*sys.argv[1:3])
